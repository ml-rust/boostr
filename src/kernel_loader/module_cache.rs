//! CUDA fatbin lookup and per-device module cache, shared by the `ops` and
//! `quant` kernel loaders.
//!
//! Fatbins are compiled by `build.rs` and embedded into the binary as byte
//! slices (see `kernels_embedded.rs`, generated into `OUT_DIR` and pulled in
//! below via `include!`). Modules are loaded from those bytes on first use
//! and cached per-device. The cache uses `OnceLock<Mutex<HashMap>>` so
//! concurrent CUDA streams can share a loaded module safely.
//!
//! Errors are plain `String`s: `ops` and `quant` each wrap them into their
//! own `Error` variant (`KernelError`, `QuantError`).

use cudarc::driver::safe::{CudaContext, CudaFunction, CudaModule};
use cudarc::nvrtc::Ptx;
use std::collections::HashMap;
use std::sync::{Arc, Mutex, OnceLock};

// Generated by build.rs: `pub static KERNELS: &[(&str, &[u8])]`, one entry
// per fatbin compiled from the kernel sources under `src/ops/cuda/kernels`
// and `src/quant/cuda/kernels`.
include!(concat!(env!("OUT_DIR"), "/kernels_embedded.rs"));

/// Look up a compiled fatbin's embedded bytes by module name.
///
/// # Errors
///
/// Returns an error naming the module when it was not compiled into this
/// binary (a name typo, or a kernel gated out at build time).
pub(crate) fn embedded_fatbin(name: &str) -> Result<&'static [u8], String> {
    KERNELS
        .iter()
        .find(|(n, _)| *n == name)
        .map(|(_, bytes)| *bytes)
        .ok_or_else(|| {
            format!(
                "CUDA module '{name}' was not compiled into this binary. \
                 It is missing from the embedded kernel table generated by build.rs — \
                 check the module name against `KERNELS` in kernels_embedded.rs."
            )
        })
}

#[allow(clippy::type_complexity)]
static MODULE_CACHE: OnceLock<Mutex<HashMap<(usize, &'static str), Arc<CudaModule>>>> =
    OnceLock::new();

/// Get or load a CUDA module from its embedded fatbin.
pub(crate) fn get_or_load_module(
    context: &Arc<CudaContext>,
    device_index: usize,
    module_name: &'static str,
) -> Result<Arc<CudaModule>, String> {
    let cache = MODULE_CACHE.get_or_init(|| Mutex::new(HashMap::new()));
    let mut guard = cache
        .lock()
        .map_err(|e| format!("kernel cache mutex poisoned: {e}"))?;

    let key = (device_index, module_name);
    if let Some(module) = guard.get(&key) {
        return Ok(module.clone());
    }

    let bytes = embedded_fatbin(module_name)?;
    let ptx = Ptx::from_binary(bytes.to_vec());
    let module = context.load_module(ptx).map_err(|e| {
        format!(
            "Failed to load CUDA module '{module_name}': {e:?}. \
             Ensure CUDA kernels were compiled correctly by build.rs."
        )
    })?;

    guard.insert(key, module.clone());
    Ok(module)
}

/// Get a kernel function from a loaded module.
pub(crate) fn get_kernel_function(
    module: &Arc<CudaModule>,
    kernel_name: &str,
) -> Result<CudaFunction, String> {
    module.load_function(kernel_name).map_err(|e| {
        format!(
            "Failed to get kernel '{kernel_name}': {e:?}. \
             Check that the kernel name matches the CUDA source."
        )
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn unknown_module_name_errors() {
        assert!(embedded_fatbin("this_module_does_not_exist").is_err());
    }

    #[test]
    fn embedded_table_is_not_empty() {
        assert!(
            !KERNELS.is_empty(),
            "build.rs compiled no CUDA kernels into KERNELS"
        );
    }
}
