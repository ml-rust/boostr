    #[test]
    fn embedded_table_covers_every_named_module() {
        for name in all_module_names() {
            assert!(
                embedded_fatbin(name).is_ok(),
                "module '{name}' is named in quant/cuda/kernels/constants.rs but \
                 missing from the embedded KERNELS table generated by build.rs"
            );
        }
    }

    #[test]
    fn mma_modules_follow_the_format_infix() {
        for (infix, module) in QUANT_MMQ_MMA_MODULES {
            assert_eq!(module, format!("quant_mmq_mma_{infix}"));
            assert_eq!(quant_mmq_mma_module(infix), Some(module));
        }
        assert_eq!(quant_mmq_mma_module("q8_k"), None);
    }

